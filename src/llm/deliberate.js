// 第二遍：让副模型对自己刚出的分镜做逻辑思辨（省主模型这块的 CoT）
export function buildDeliberateMessages({ briefText, draft }) {
    const sys = [
        '你是这本小说的「逻辑审校」。上一遍已经给出这一轮的分镜草稿，你要挑逻辑问题并改掉。',
        '只输出一个 JSON 对象，不要解释。字段：',
        '{',
        '  "problems": ["发现的问题，每条≤16字，最多 4 条"],',
        '  "beats": [{"who":"谁","do":"做什么（≤18字）"}],',
        '  "hook": "末了留什么（≤18字）",',
        '  "minutes": 数字（如果原来的时间推进不合理，改掉）',
        '}',
        '',
        '重点查这几类：',
        '1) 时间：这一轮的事放得下吗？该跨日却只给几分钟，或反之。',
        '2) 在场：beats 里有没有出现不在场的人；上一幕在场的人有没有凭空消失。',
        '3) 状态：上一幕的伤、病、手里拿的东西，有没有被忘掉。',
        '4) 职权：没这项权的人有没有办这事（文官调兵、仆役问案）。',
        '5) 忌：有没有让人物碰到自己的底线。',
        '6) 因果：beats 之间跳步了吗？需要一个中间动作吗。',
        '7) 礼法：这一场的礼法候选有没有被用错对象。',
        '',
        '没问题就 problems 写空数组，beats 原样返回。改动要小，不要另起情节。',
    ].join('\n');

    const user = [
        briefText || '（无背景）',
        '',
        '【分镜草稿】',
        JSON.stringify(draft ?? {}, null, 1),
    ].join('\n');

    return [
        { role: 'system', content: sys },
        { role: 'user', content: user },
    ];
}
